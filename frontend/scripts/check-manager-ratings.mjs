import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root = new URL('../dist/tools/manager-ratings/', import.meta.url);
const html = readFileSync(new URL('index.html',root),'utf8');
const data = JSON.parse(readFileSync(new URL('manager-elo-data.json',root),'utf8'));
assert.equal(data.access,'public');
assert.ok(data.rows.length > 3);
const body = html.match(/<tbody id="body">([\s\S]*?)<\/tbody>/)[1];
assert.equal((body.match(/<tr /g)||[]).length,data.rows.filter(r=>r.eligible).length);
for (const row of data.rows.filter(r=>r.eligible)) assert.ok(body.includes(`data-id="${row.id}"`));
assert.equal(body.includes('rank-move up'), data.rows.some(r=>r.eligible && r.rank_movement>0));
assert.equal(body.includes('rank-move down'), data.rows.some(r=>r.eligible && r.rank_movement<0));
assert.ok(!html.includes('id="manager-paywall"'));
assert.ok(!html.includes('require SteamWatch Pro'));
assert.equal((html.match(/<h1>/g)||[]).length,1);
assert.equal((html.match(/rel="canonical"/g)||[]).length,1);
const schemas = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].flatMap(m=>JSON.parse(m[1]));
assert.ok(schemas.some(s=>s['@type']==='Dataset' && s.isAccessibleForFree));
assert.ok(schemas.some(s=>s['@type']==='FAQPage' && s.mainEntity.length===6));
assert.ok(html.includes(data.as_of.slice(0,10)));
console.log('Public HTML, movement arrows, canonical and structured data checks passed.');
